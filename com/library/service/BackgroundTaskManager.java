package com.library.service;

import com.library.model.Book;
import java.util.List;
import java.util.concurrent.Callable;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.ThreadFactory;
import java.util.concurrent.atomic.AtomicInteger;

/** Runs non-interactive library work on named background worker threads. */
public class BackgroundTaskManager implements AutoCloseable {
    private final ExecutorService executor;

    public BackgroundTaskManager() {
        AtomicInteger counter = new AtomicInteger(1);
        ThreadFactory factory = task -> {
            Thread thread = new Thread(task, "library-worker-" + counter.getAndIncrement());
            thread.setDaemon(false);
            return thread;
        };
        this.executor = Executors.newFixedThreadPool(2, factory);
    }

    public Future<String> generateInventoryReport(BookOperations bookOperations) {
        Callable<String> task = () -> {
            List<Book> books = bookOperations.getAllBooks();
            long available = books.stream().filter(b -> "Available".equals(b.getStatus())).count();
            long issued = books.stream().filter(b -> "Issued".equals(b.getStatus())).count();
            return "Inventory report generated by " + Thread.currentThread().getName() + "\n"
                    + "Total books: " + books.size() + "\n"
                    + "Available: " + available + "\n"
                    + "Issued: " + issued;
        };
        return executor.submit(task);
    }

    @Override
    public void close() {
        executor.shutdown();
    }
}
